const catalogs: Record<PortalLocale, Catalog> = { de, ru, en };

export function isPortalLocale(value: unknown): value is PortalLocale {
  return (
    typeof value === "string" && PORTAL_LOCALES.includes(value as PortalLocale)
  );
}

export function resolvePortalLocale(value: unknown): PortalLocale {
  return isPortalLocale(value) ? value : DEFAULT_PORTAL_LOCALE;
}

export function translate(
  locale: PortalLocale,
  key: MessageKey,
  values: Readonly<Record<string, string | number>> = {},
): string {
  const template = catalogs[locale][key] ?? de[key];
  return template.replace(/\{([a-zA-Z0-9_]+)\}/g, (_, name: string) =>
    String(values[name] ?? `{${name}}`),
  );
}

export function intlLocale(locale: PortalLocale): string {
  return locale === "de" ? "de-DE" : locale === "ru" ? "ru-RU" : "en-GB";
}
